#!/bin/sh
set -eu

# Xcode Cloud post-clone hook.
# Generates the gitignored Secrets.xcconfig from Xcode Cloud environment variables
# when configured in App Store Connect. The .xcodeproj itself is committed so
# Xcode Cloud can inspect shared schemes and archive actions before clone hooks run.

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IOS_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
SECRETS_FILE="${IOS_DIR}/Config/Secrets.xcconfig"

if [ ! -f "${SECRETS_FILE}" ]; then
  {
    echo "// Generated by ci_post_clone.sh"
    if [ -n "${CLERK_PUBLISHABLE_KEY:-}" ]; then
      echo "CLERK_PUBLISHABLE_KEY = ${CLERK_PUBLISHABLE_KEY}"
    fi
    if [ -n "${CONVEX_SITE_HOST:-}" ]; then
      echo "CONVEX_SITE_HOST = ${CONVEX_SITE_HOST}"
    fi
  } > "${SECRETS_FILE}"
fi
